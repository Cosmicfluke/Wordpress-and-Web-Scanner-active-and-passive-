# WAF detection module.
# Passively fingerprints firewalls via headers, cookies, and body content.
# When a WAF is detected, core.py enables WAF evasion mode automatically.

import re
from colorama import Fore, Style
from utils.http import get
from utils.severity import finding, INFO

