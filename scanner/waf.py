def _score(resp, sig):
    h  = {k.lower(): v.lower() for k, v in resp.headers.items()}
    ck = resp.headers.get("Set-Cookie", "").lower()
    sv = h.get("server", "")
    b  = resp.text[:4000]
    s  = 0
    for hdr in sig["headers"]: s += 3 if hdr in h else 0
    for sv_ in sig["server"]:  s += 3 if sv_ in sv else 0
    for ck_ in sig["cookies"]: s += 2 if ck_ in ck else 0
    for pat in sig["body"]:    s += 2 if re.search(pat, b, re.I) else 0
    return s


def detect(base_url, resp=None):
    resp = resp or get(base_url)
    if resp is None:
        return {"detected": False, "name": None, "confidence": None}

    for sig in WAF_SIGNATURES:
        score = _score(resp, sig)
        if score >= 3:
            return {
                "detected"  : True,
                "name"      : sig["name"],
                "confidence": "high" if score >= 6 else "medium",
            }

    # Try triggering the WAF with a malicious-looking request.
    trigger = get(f"{base_url.rstrip('/')}/?s=<script>alert(1)</script>&id=1+UNION+SELECT+1,2--")
    if trigger and trigger.status_code in (403, 406, 429, 503):
        for sig in WAF_SIGNATURES:
            for pat in sig["body"]:
                if re.search(pat, trigger.text[:4000], re.I):
                    return {"detected": True, "name": sig["name"], "confidence": "medium"}
        return {"detected": True, "name": "Unknown WAF", "confidence": "low"}

    return {"detected": False, "name": None, "confidence": None}


def run(base_url, resp=None):
    print(f"{Fore.CYAN}[*] Checking for WAF / firewall...{Style.RESET_ALL}")
    result   = detect(base_url, resp)
    findings = []

    if result["detected"]:
        name = result["name"]
        conf = result["confidence"]
        print(f"{Fore.YELLOW}[!] WAF detected: {name} (confidence: {conf}){Style.RESET_ALL}")
        print(f"{Fore.YELLOW}    Enabling WAF evasion mode{Style.RESET_ALL}")
        findings.append(finding(
            title       = f"WAF Detected: {name}",
            severity    = INFO,
            description = f"{name} firewall detected (confidence: {conf}).",
            impact      = "Active scanning may be blocked or return false negatives.",
            remediation = "For tester: use --stealth. For client: verify WAF rules are correctly configured.",
            evidence    = f"WAF: {name} | Confidence: {conf}",
        ))
    else:
        print(f"{Fore.GREEN}[+] No WAF detected{Style.RESET_ALL}")

    return result, findings
